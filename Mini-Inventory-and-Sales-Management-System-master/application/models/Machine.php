<?php
defined('BASEPATH') OR exit('');

/**
 * Description of Machine
 *
 * Machine model for Manufacturing Production & Quality Management
 */
class Machine extends CI_Model{
    public function __construct(){
        parent::__construct();
    }
    
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
    /**
     * Get all machines with pagination
     * @param type $orderBy
     * @param type $orderFormat
     * @param type $start
     * @param type $limit
     * @return boolean
     */
    public function getAll($orderBy, $orderFormat, $start=0, $limit=''){
        $this->db->limit($limit, $start);
        $this->db->order_by($orderBy, $orderFormat);
        
        $run_q = $this->db->get('machines');
        
        if($run_q->num_rows() > 0){
            return $run_q->result();
        }
        
        else{
            return FALSE;
        }
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Add a new machine
     * @param type $name
     * @param type $code
     * @param type $type
     * @param type $location
     * @param type $notes
     * @return boolean
     */
    public function add($name, $code, $type, $location, $notes){
        $data = ['name'=>$name, 'code'=>$code, 'type'=>$type, 'location'=>$location, 'notes'=>$notes];
                
        //set the datetime based on the db driver in use
        $this->db->platform() == "sqlite3" 
                ? 
        $this->db->set('dateAdded', "datetime('now')", FALSE) 
                : 
        $this->db->set('dateAdded', "NOW()", FALSE);
        
        $this->db->insert('machines', $data);
        
        if($this->db->insert_id()){
            return $this->db->insert_id();
        }
        
        else{
            return FALSE;
        }
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Edit a machine
     * @param type $id
     * @param type $name
     * @param type $type
     * @param type $location
     * @param type $notes
     */
    public function edit($id, $name, $type, $location, $notes){
        $data = ['name'=>$name, 'type'=>$type, 'location'=>$location, 'notes'=>$notes];
        
        $this->db->where('id', $id);
        $this->db->update('machines', $data);
        
        return TRUE;
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Update machine status
     * @param type $id
     * @param type $status
     * @return boolean
     */
    public function updateStatus($id, $status){
        $data = ['status'=>$status];
        
        $this->db->where('id', $id);
        $this->db->update('machines', $data);
        
        if($this->db->affected_rows() > 0){
            return TRUE;
        }
        
        else{
            return FALSE;
        }
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Delete a machine
     * @param type $id
     * @return boolean
     */
    public function delete($id){
        $this->db->where('id', $id);
        $this->db->delete('machines');
        
        if($this->db->affected_rows() > 0){
            return TRUE;
        }
        
        else{
            return FALSE;
        }
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Get total number of machines
     * @return boolean
     */
    public function totalMachines(){
        $q = "SELECT COUNT(*) as 'totalMachines' FROM machines";
        
        $run_q = $this->db->query($q);
        
        if($run_q->num_rows() > 0){
            foreach($run_q->result() as $get){
                return $get->totalMachines;
            }
        }
        
        else{
            return FALSE;
        }
    }
    
    /*
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    ********************************************************************************************************************************
    */
    
    /**
     * Get machine counts grouped by status
     * @return boolean
     */
    public function getMachinesByStatus(){
        $q = "SELECT status, COUNT(*) as 'count' FROM machines GROUP BY status";
        
        $run_q = $this->db->query($q);
        
        if($run_q->num_rows() > 0){
            return $run_q->result();
        }
        
        else{
            return FALSE;
        }
    }
}
